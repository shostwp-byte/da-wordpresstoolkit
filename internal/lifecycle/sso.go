const DefaultSSOTTLSeconds = 45

// SSOResult contains the single-use wp-admin login URL valid for 45 seconds.
type SSOResult struct {
	LoginURL   string `json:"login_url"`
	ExpiresIn  int    `json:"expires_in"`
	TargetUser string `json:"target_user,omitempty"`
}

// CreateEphemeralSSO writes a self-destructing one-time MU-plugin token (SHA-256 hashed, 45s TTL)
// and schedules a background reaper after 60s to guarantee zero plugin residue.
func (m *Manager) CreateEphemeralSSO(acct dausers.Account, inst store.InstanceRecord, targetAdmin string) (SSOResult, error) {
	targetAdmin = strings.TrimSpace(targetAdmin)
	if targetAdmin != "" {
		if err := config.ValidateIdentifier(targetAdmin); err != nil {
			return SSOResult{}, fmt.Errorf("invalid admin username: %w", err)
		}
	}

	domainsRoot := filepath.Join(filepath.Clean(acct.HomeDir), "domains")
	guard, err := fsguard.New(domainsRoot, nil)
	if err != nil {
		return SSOResult{}, err
	}
	verifiedRoot, err := guard.VerifyExistingPath(inst.DocRoot)
	if err != nil {
		return SSOResult{}, err
	}

	muDir := filepath.Join(verifiedRoot, "wp-content", "mu-plugins")
	if _, err := guard.VerifyProspectivePath(muDir); err != nil {
		return SSOResult{}, err
	}
	if err := ensureOwnedDir(filepath.Join(verifiedRoot, "wp-content"), acct.UID, acct.GID, 0o755); err != nil {
		return SSOResult{}, err
	}
	if err := ensureOwnedDir(muDir, acct.UID, acct.GID, 0o755); err != nil {
		return SSOResult{}, err
	}

	var tokenBytes [32]byte
	if _, err := rand.Read(tokenBytes[:]); err != nil {
		return SSOResult{}, err
	}
	rawToken := hex.EncodeToString(tokenBytes[:])
	sum := sha256.Sum256([]byte(rawToken))
	tokenSHA256 := hex.EncodeToString(sum[:])

	ttl := m.SSOTTLSeconds
	if ttl <= 0 {
		ttl = DefaultSSOTTLSeconds
	}
	expiresAt := time.Now().Unix() + int64(ttl)

	fileName := ".da-wptk-sso-" + tokenSHA256[:12] + ".php"
	muFilePath := filepath.Join(muDir, fileName)
	if info, lErr := os.Lstat(muFilePath); lErr == nil && info.Mode()&os.ModeSymlink != 0 {
		return SSOResult{}, fsguard.ErrSymlinkBlocked
	}

	phpCode := renderEphemeralSSOMUPlugin(tokenSHA256, expiresAt, targetAdmin)
	if err := writeOwnedFile(muFilePath, []byte(phpCode), acct.UID, acct.GID, 0o640); err != nil {
		return SSOResult{}, err
	}

	// Background reaper ensures zero leftover file even if user closes browser tab before visiting URL
	reapDelay := time.Duration(ttl+15) * time.Second
	if m.ReapDelayOverride > 0 {
		reapDelay = m.ReapDelayOverride
	}
	time.AfterFunc(reapDelay, func() {
		_ = os.Remove(muFilePath)
	})

	baseURL := strings.TrimRight(inst.SiteURL, "/")
	if baseURL == "" {
		scheme := "http://"
		if inst.SSLActive {
			scheme = "https://"
		}
		baseURL = scheme + inst.Domain + inst.SubPath
	}

	loginURL := baseURL + "/wp-login.php?dawptk_sso=" + url.QueryEscape(rawToken)
	return SSOResult{
		LoginURL:   loginURL,
		ExpiresIn:  ttl,
		TargetUser: targetAdmin,
	}, nil
}

func renderEphemeralSSOMUPlugin(expectedSHA256 string, expiresAt int64, targetAdmin string) string {
	escapedAdmin := strings.ReplaceAll(strings.ReplaceAll(targetAdmin, `\`, `\\`), `'`, `\'`)
	return fmt.Sprintf(`<?php
/**
 * Ephemeral Single-Use SSO Token generated by DA-WordPressToolkits.
 * Automatically self-destructs on first use or expiration.
 */
if (!defined('ABSPATH')) {
    exit;
}

add_action('init', static function () {
    $exp = %d;
    if (time() > $exp) {
        @unlink(__FILE__);
        return;
    }
    if (!isset($_GET['dawptk_sso']) || !is_string($_GET['dawptk_sso'])) {
        return;
    }
    $providedHash = hash('sha256', $_GET['dawptk_sso']);
    if (!hash_equals('%s', $providedHash)) {
        return;
    }

    // Consume one-time token immediately before authenticating to prevent replay
    @unlink(__FILE__);

    $wanted = '%s';
    $user = null;
    if ($wanted !== '') {
        $candidate = get_user_by('login', $wanted);
        if ($candidate && user_can($candidate, 'manage_options')) {
            $user = $candidate;
        }
    }
    if (!$user) {
        $admins = get_users([
            'role'    => 'administrator',
            'orderby' => 'ID',
            'order'   => 'ASC',
            'number'  => 1,
        ]);
        if (!empty($admins)) {
            $user = $admins[0];
        }
    }
    if (!$user) {
        wp_die('No WordPress Administrator account found on this site.');
    }

    wp_clear_auth_cookie();
    wp_set_current_user($user->ID);
    wp_set_auth_cookie($user->ID, false, is_ssl());
    do_action('wp_login', $user->user_login, $user);

    wp_safe_redirect(admin_url());
    exit;
}, 1);
`, expiresAt, expectedSHA256, escapedAdmin)
}
